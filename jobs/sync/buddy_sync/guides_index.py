"""GUIDES_INDEX.md: a generated, drift-checked table of the Guides headings (D-23).

The chunker's ``heading_outline`` is the single heading parser; this module renders its
output as a markdown table, reads that table back, and compares it with the actual
headings. At sync time the chunker output is authoritative: drift is logged as a warning,
and strict mode turns it into ``GuidesIndexDriftError``.

The table format is a cross-repo contract: the file lives in the Guides repo, so changing
the columns means regenerating it there and updating ``parse_guides_index`` together.
"""

import logging
import re
from collections import defaultdict
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path, PurePosixPath, PureWindowsPath
from typing import Final, Literal

from buddy_sync.chunker import Heading

GUIDES_INDEX_NAME: Final = "GUIDES_INDEX.md"
_HEADER: Final = "<!-- generated by buddy_sync guides-index; do not edit by hand -->"
_COLUMNS: Final = "| File | Level | Section | Line |"
_SEPARATOR: Final = "| --- | --- | --- | --- |"
_CELL_SPLIT: Final = re.compile(r"(?<!\\)\|")


@dataclass(frozen=True, slots=True)
class IndexEntry:
    """One row of GUIDES_INDEX.md; ``line`` is 1-based."""

    file: str
    level: int
    title: str
    line: int


@dataclass(frozen=True, slots=True)
class Drift:
    """One disagreement between GUIDES_INDEX.md and the actual headings."""

    kind: Literal["missing", "extra", "moved", "absent_file"]
    file: str
    title: str
    declared_line: int | None
    actual_line: int | None


class GuidesIndexDriftError(Exception):
    """GUIDES_INDEX.md disagrees with the headings of the Guides."""


def _escape(title: str) -> str:
    return title.replace("|", "\\|")


def _unescape(cell: str) -> str:
    return cell.replace("\\|", "|")


def render_guides_index(outline: Mapping[str, Sequence[Heading]]) -> str:
    """Render the outline as the generated markdown file, rows sorted by file then line."""
    lines = [_HEADER, "", "# Guides Index", "", _COLUMNS, _SEPARATOR]
    for file in sorted(outline):
        for heading in sorted(outline[file], key=lambda h: h.line):
            lines.append(
                f"| {file} | {heading.level} | {_escape(heading.title)} | {heading.line} |"
            )
    return "\n".join(lines) + "\n"


def _check_path(file: str) -> None:
    posix = PurePosixPath(file)
    if posix.is_absolute() or PureWindowsPath(file).is_absolute() or ".." in posix.parts:
        raise ValueError(f"GUIDES_INDEX.md row has an unsafe path: {file!r}")


def parse_guides_index(text: str) -> list[IndexEntry]:
    """Read the table back; rows with absolute or ``..`` paths raise ``ValueError``."""
    entries: list[IndexEntry] = []
    for raw in text.splitlines():
        row = raw.strip()
        if not row.startswith("|") or row in (_COLUMNS, _SEPARATOR):
            continue
        cells = [cell.strip() for cell in _CELL_SPLIT.split(row.strip("|"))]
        if len(cells) != 4:
            raise ValueError(f"GUIDES_INDEX.md row is malformed: {row!r}")
        file, level, title, line = cells
        _check_path(file)
        try:
            entries.append(IndexEntry(file, int(level), _unescape(title), int(line)))
        except ValueError:
            raise ValueError(f"GUIDES_INDEX.md row is malformed: {row!r}") from None
    return entries


def _lines_by_key(
    entries: Sequence[tuple[int, str, int]],
) -> dict[tuple[int, str], list[int]]:
    grouped: dict[tuple[int, str], list[int]] = defaultdict(list)
    for level, title, line in entries:
        grouped[(level, title)].append(line)
    return {key: sorted(lines) for key, lines in grouped.items()}


def compare_guides_index(
    declared: Sequence[IndexEntry], actual_outline: Mapping[str, Sequence[Heading]]
) -> list[Drift]:
    """Compare by (file, level, title) for missing and extra, and by line for moved."""
    declared_by_file: dict[str, list[tuple[int, str, int]]] = defaultdict(list)
    for entry in declared:
        declared_by_file[entry.file].append((entry.level, entry.title, entry.line))
    drifts: list[Drift] = []
    for file in sorted(set(declared_by_file) | set(actual_outline)):
        if file not in actual_outline:
            drifts.append(Drift("absent_file", file, "", None, None))
            continue
        declared_keys = _lines_by_key(declared_by_file.get(file, []))
        actual_keys = _lines_by_key([(h.level, h.title, h.line) for h in actual_outline[file]])
        file_drifts: list[Drift] = []
        for key in sorted(set(declared_keys) | set(actual_keys), key=lambda k: (k[0], k[1])):
            was = declared_keys.get(key, [])
            now = actual_keys.get(key, [])
            title = key[1]
            for old, new in zip(was, now, strict=False):
                if old != new:
                    file_drifts.append(Drift("moved", file, title, old, new))
            file_drifts.extend(Drift("missing", file, title, old, None) for old in was[len(now) :])
            file_drifts.extend(Drift("extra", file, title, None, new) for new in now[len(was) :])
        file_drifts.sort(key=lambda d: (d.declared_line or d.actual_line or 0, d.kind))
        drifts.extend(file_drifts)
    return drifts


def check_guides_index(
    root: Path,
    outline: Mapping[str, Sequence[Heading]],
    *,
    strict: bool,
    logger: logging.Logger,
) -> list[Drift]:
    """Warn about every drift between ``root/GUIDES_INDEX.md`` and the outline.

    A missing file is also a warning. Strict mode raises ``GuidesIndexDriftError`` instead
    of only warning.
    """
    path = root / GUIDES_INDEX_NAME
    if not path.is_file():
        logger.warning("guides_index missing file=%s", GUIDES_INDEX_NAME)
        if strict:
            raise GuidesIndexDriftError(f"{GUIDES_INDEX_NAME} is missing")
        return []
    drifts = compare_guides_index(parse_guides_index(path.read_text(encoding="utf-8")), outline)
    for drift in drifts:
        logger.warning(
            "guides_index drift kind=%s file=%s section=%s", drift.kind, drift.file, drift.title
        )
    if drifts and strict:
        raise GuidesIndexDriftError(
            f"{GUIDES_INDEX_NAME} has {len(drifts)} drift(s) from the Guides"
        )
    return drifts


def write_guides_index(root: Path, outline: Mapping[str, Sequence[Heading]]) -> Path:
    """Write the generated file to ``root/GUIDES_INDEX.md`` and return its path."""
    path = root / GUIDES_INDEX_NAME
    path.write_text(render_guides_index(outline), encoding="utf-8")
    return path
