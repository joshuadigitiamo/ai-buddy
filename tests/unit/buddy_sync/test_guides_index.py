"""GUIDES_INDEX.md: generated from the chunker's outline and drift-checked (D-23)."""

import logging
from pathlib import Path

import pytest

from buddy_sync.chunker import Heading
from buddy_sync.guides_index import (
    GUIDES_INDEX_NAME,
    Drift,
    GuidesIndexDriftError,
    IndexEntry,
    check_guides_index,
    compare_guides_index,
    parse_guides_index,
    render_guides_index,
    write_guides_index,
)

LOGGER = logging.getLogger("buddy_sync.test")
HEADER = "<!-- generated by buddy_sync guides-index; do not edit by hand -->"

OUTLINE = {
    "Foundations/B_GUIDE.md": [Heading(2, "1. Intro", 3), Heading(3, "Why", 5)],
    "AI-Engineering/A_GUIDE.md": [Heading(2, "1. Basics", 3), Heading(3, "Chunking", 7)],
}


def _entries(outline: dict[str, list[Heading]]) -> list[IndexEntry]:
    return parse_guides_index(render_guides_index(outline))


def test_render_then_parse_round_trips_every_heading() -> None:
    entries = _entries(OUTLINE)
    expected = [
        IndexEntry(file, h.level, h.title, h.line)
        for file in sorted(OUTLINE)
        for h in sorted(OUTLINE[file], key=lambda h: h.line)
    ]
    assert entries == expected


def test_rendered_file_starts_with_the_generated_comment_and_has_a_table() -> None:
    lines = render_guides_index(OUTLINE).splitlines()
    assert lines[0] == HEADER
    assert "# Guides Index" in lines
    assert "| File | Level | Section | Line |" in lines


def test_output_is_ordered_by_file_then_line() -> None:
    shuffled = {
        "Z/Z_GUIDE.md": [Heading(3, "late", 9), Heading(2, "early", 2)],
        "A/A_GUIDE.md": [Heading(2, "only", 4)],
    }
    entries = _entries(shuffled)
    assert [(e.file, e.line) for e in entries] == [
        ("A/A_GUIDE.md", 4),
        ("Z/Z_GUIDE.md", 2),
        ("Z/Z_GUIDE.md", 9),
    ]


def test_pipe_in_a_title_survives_the_round_trip() -> None:
    outline = {"A/A_GUIDE.md": [Heading(2, "Cache | Queue", 1)]}
    assert [e.title for e in _entries(outline)] == ["Cache | Queue"]


def test_renamed_heading_reports_one_missing_and_one_extra() -> None:
    declared = _entries(OUTLINE)
    actual = {
        **OUTLINE,
        "AI-Engineering/A_GUIDE.md": [Heading(2, "1. Basics", 3), Heading(3, "Splitting", 7)],
    }
    drifts = compare_guides_index(declared, actual)
    assert sorted((d.kind, d.title) for d in drifts) == [
        ("extra", "Splitting"),
        ("missing", "Chunking"),
    ]
    missing = next(d for d in drifts if d.kind == "missing")
    assert (missing.declared_line, missing.actual_line) == (7, None)


def test_inserted_line_reports_a_moved_heading_with_both_line_numbers() -> None:
    declared = _entries(OUTLINE)
    actual = {
        **OUTLINE,
        "AI-Engineering/A_GUIDE.md": [Heading(2, "1. Basics", 3), Heading(3, "Chunking", 8)],
    }
    assert compare_guides_index(declared, actual) == [
        Drift("moved", "AI-Engineering/A_GUIDE.md", "Chunking", 7, 8)
    ]


def test_file_declared_but_gone_is_reported_as_absent_file() -> None:
    declared = _entries(OUTLINE)
    actual = {"AI-Engineering/A_GUIDE.md": OUTLINE["AI-Engineering/A_GUIDE.md"]}
    drifts = compare_guides_index(declared, actual)
    assert [(d.kind, d.file) for d in drifts] == [("absent_file", "Foundations/B_GUIDE.md")]


def test_matching_outline_has_no_drift(tmp_path: Path, caplog: pytest.LogCaptureFixture) -> None:
    write_guides_index(tmp_path, OUTLINE)
    with caplog.at_level(logging.WARNING):
        assert check_guides_index(tmp_path, OUTLINE, strict=True, logger=LOGGER) == []
    assert caplog.records == []


def test_drift_is_logged_as_warning_and_strict_mode_raises(
    tmp_path: Path, caplog: pytest.LogCaptureFixture
) -> None:
    write_guides_index(tmp_path, OUTLINE)
    actual = {
        **OUTLINE,
        "AI-Engineering/A_GUIDE.md": [Heading(2, "1. Basics", 3), Heading(3, "Chunking", 8)],
    }
    with caplog.at_level(logging.WARNING):
        drifts = check_guides_index(tmp_path, actual, strict=False, logger=LOGGER)
    assert [d.kind for d in drifts] == ["moved"]
    warnings = [r.getMessage() for r in caplog.records if r.levelno == logging.WARNING]
    assert warnings == [
        "guides_index drift kind=moved file=AI-Engineering/A_GUIDE.md section=Chunking"
    ]
    with pytest.raises(GuidesIndexDriftError):
        check_guides_index(tmp_path, actual, strict=True, logger=LOGGER)


def test_absent_index_file_warns_and_strict_mode_raises(
    tmp_path: Path, caplog: pytest.LogCaptureFixture
) -> None:
    with caplog.at_level(logging.WARNING):
        assert check_guides_index(tmp_path, OUTLINE, strict=False, logger=LOGGER) == []
    assert any(GUIDES_INDEX_NAME in r.getMessage() for r in caplog.records)
    with pytest.raises(GuidesIndexDriftError):
        check_guides_index(tmp_path, OUTLINE, strict=True, logger=LOGGER)


@pytest.mark.parametrize("bad_path", ["/etc/passwd", "../outside/X_GUIDE.md", "a/../../b_GUIDE.md"])
def test_rows_with_absolute_or_parent_paths_are_rejected(bad_path: str) -> None:
    text = "\n".join(
        [
            HEADER,
            "",
            "# Guides Index",
            "",
            "| File | Level | Section | Line |",
            "| --- | --- | --- | --- |",
            f"| {bad_path} | 2 | S | 1 |",
            "",
        ]
    )
    with pytest.raises(ValueError, match="path"):
        parse_guides_index(text)


def test_write_guides_index_writes_the_rendered_text(tmp_path: Path) -> None:
    path = write_guides_index(tmp_path, OUTLINE)
    assert path == tmp_path / GUIDES_INDEX_NAME
    assert path.read_text(encoding="utf-8") == render_guides_index(OUTLINE)
