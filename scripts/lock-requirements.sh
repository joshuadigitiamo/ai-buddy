#!/usr/bin/env bash
# Regenerate every hashed dependency lock inside Docker (INFRA-01, INFRA-06, review WR-04).
#
# One container, started from the same base image as the Dockerfile's first FROM line, installs
# the approved pip-tools into a throwaway venv under /tmp and compiles:
#   1. requirements-dev.lock                   from requirements-dev.txt (the tested image)
#   2. services/mcp_server/requirements.lock   from requirements.txt + the service file
#      services/chat_bot/requirements.lock
#      jobs/sync/requirements.lock
#      jobs/eval/requirements.lock   from requirements.txt + the chat_bot file + its own file
# The stage locks are compiled with the pins of requirements-dev.lock as a constraint, so the
# shipped images resolve the same versions as the tested image. Every lock carries sha256 hashes;
# the Dockerfile installs them with `pip install --require-hashes`.
#
# pip-tools lives only in that throwaway container: never in an image or requirements-dev.txt.
# Locks resolve for linux/amd64 and CPython 3.12 (the base image).
#
# Usage:
#   scripts/lock-requirements.sh        (no arguments; needs network access to PyPI)

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"

# Version approved at the 04-18 package legitimacy gate (04-18-SUMMARY.md, `## pip-tools approval`).
PIP_TOOLS="pip-tools==7.6.2"

log() { echo "[lock-requirements] $*"; }
die() { echo "[lock-requirements] ERROR: $*" >&2; exit 1; }

[[ $# -eq 0 ]] || die "takes no arguments"

# The first FROM line is the base of every stage; a digest pin added there flows in unedited.
BASE_IMAGE="$(awk '/^FROM /{print $2; exit}' "${ROOT_DIR}/Dockerfile")"
[[ -n "${BASE_IMAGE}" ]] || die "no FROM line in Dockerfile"
log "base image: ${BASE_IMAGE}; ${PIP_TOOLS}"

# Runs inside the container, in /repo. Plain `bash -c` text, no tracing, no secrets involved.
IFS= read -r -d '' INNER <<'INNER_END' || true
set -euo pipefail
python -m venv /tmp/lock-venv
/tmp/lock-venv/bin/pip install --quiet --disable-pip-version-check "${PIP_TOOLS}"
compile() {
  /tmp/lock-venv/bin/pip-compile --quiet --generate-hashes --allow-unsafe --strip-extras \
    --no-header --output-file "$@"
}
add_header() {
  {
    echo "# Generated by scripts/lock-requirements.sh; the via lines name the requirement files."
    echo "# Do not edit by hand. Install with: pip install --require-hashes -r <this file>"
    cat "$1"
  } > /tmp/with-header
  cp /tmp/with-header "$1"
}

compile requirements-dev.lock requirements-dev.txt
add_header requirements-dev.lock
# Pins only, no hashes: the constraint that keeps the stage locks on the tested versions.
sed -nE 's/^([A-Za-z0-9._-]+==[^ ]+).*/\1/p' requirements-dev.lock > /tmp/constraints.txt

compile_stage() {
  local lock="$1"; shift
  compile "${lock}" --constraint /tmp/constraints.txt "$@"
  add_header "${lock}"
}
compile_stage services/mcp_server/requirements.lock requirements.txt services/mcp_server/requirements.txt
compile_stage services/chat_bot/requirements.lock requirements.txt services/chat_bot/requirements.txt
compile_stage jobs/sync/requirements.lock requirements.txt jobs/sync/requirements.txt
compile_stage jobs/eval/requirements.lock requirements.txt services/chat_bot/requirements.txt jobs/eval/requirements.txt
INNER_END

log "compiling five locks in Docker ..."
docker run --rm \
  --user "$(id -u):$(id -g)" \
  -e HOME=/tmp \
  -e PIP_TOOLS="${PIP_TOOLS}" \
  -v "${ROOT_DIR}:/repo" \
  -w /repo \
  "${BASE_IMAGE}" bash -c "${INNER}"

log "done: requirements-dev.lock and the four stage locks regenerated"
